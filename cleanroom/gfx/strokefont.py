def _lower(c):
    # Lower-case glyphs: the upper-case design compressed into the x-height.
    up = G.get(c.upper())
    if up is None:
        return None
    return [[(x, 2 + y * 4 / 6) for x, y in line] for line in up]


def glyph(c):
    if c in G:
        return G[c]
    if c.isalpha() and c.islower():
        return _lower(c)
    return None


def render(c, w, h, thickness=None) -> np.ndarray:
    """Return an (h, w) float coverage mask in [0, 1] for character c."""
    mask = np.zeros((h, w), dtype=np.float32)
    lines = glyph(c)
    if not lines or w < 2 or h < 3:
        return mask
    pad_x = max(0.5, w * 0.12)
    pad_y = max(0.5, h * 0.1)
    sx = (w - 2 * pad_x) / 4.0
    sy = (h - 2 * pad_y) / 7.0
    th = thickness if thickness is not None else max(0.7, min(w, h) * 0.09)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32) + 0.5
    for line in lines:
        pts = [(pad_x + x * sx, pad_y + y * sy) for x, y in line]
        if len(pts) == 1:
            pts = pts * 2
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            dx, dy = x1 - x0, y1 - y0
            ll = dx * dx + dy * dy
            if ll == 0:
                d = np.hypot(xx - x0, yy - y0)
            else:
                t = np.clip(((xx - x0) * dx + (yy - y0) * dy) / ll, 0, 1)
                d = np.hypot(xx - (x0 + t * dx), yy - (y0 + t * dy))
            mask = np.maximum(mask, np.clip(th + 0.5 - d, 0, 1))
    return mask


def render_text(text, cell_w, cell_h, spacing=1) -> np.ndarray:
    out = np.zeros((cell_h, max(1, len(text) * (cell_w + spacing))), dtype=np.float32)
    for i, ch in enumerate(text):
        out[:, i * (cell_w + spacing): i * (cell_w + spacing) + cell_w] = render(ch, cell_w, cell_h)
    return out
